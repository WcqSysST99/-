#include <bits/stdc++.h>   // 包含所有标准 C++ 头文件，方便竞赛编程
using namespace std;      // 使用标准命名空间，避免频繁写 std::

const int N = 35;         // 定义最大方阵边长，30 + 额外两圈 = 32，取 35 保证安全
int a[N][N];              // 存储方阵，下标从 0 开始，外围加一圈 0
bool vis[N][N];           // 标记某个格子是否被 BFS 访问过
int n;                    // 方阵的实际边长
int dx[4] = {1, -1, 0, 0}; // 四个方向的横坐标变化量：下、上、右、左
int dy[4] = {0, 0, 1, -1}; // 四个方向的纵坐标变化量：下、上、右、左

void bfs() {              // 从 (0,0) 开始搜索所有与边界连通的 0
    queue<pair<int, int>> q; // 使用队列进行广度优先搜索，元素为坐标对
    q.push({0, 0});          // 将起点 (0,0) 入队
    vis[0][0] = true;        // 标记起点已访问

    while (!q.empty()) {     // 当队列不为空时继续搜索
        auto[x, y] = q.front(); // 取出队首坐标（C++17 结构化绑定）
        q.pop();                // 弹出队首元素

        for (int i = 0; i < 4; ++i) {     // 遍历四个方向
            int nx = x + dx[i], ny = y + dy[i]; // 计算新坐标
            if (nx < 0 || nx > n+1 || ny < 0 || ny > n+1) // 检查是否超出加了圈的方阵边界
                continue;               // 如果越界则跳过
            if (!vis[nx][ny] && a[nx][ny] == 0) { // 若未访问且该格子值为 0
                vis[nx][ny] = true;       // 标记为已访问
                q.push({nx, ny});         // 将新坐标入队，继续扩展
            }
        }
    }
}

int main() {
    cin >> n;                     // 读入方阵边长 n
    // 将方阵放在 a[1..n][1..n]，外围 a[0][*] 和 a[n+1][*] 等自动为 0
    for (int i = 1; i <= n; ++i)  // 遍历行
        for (int j = 1; j <= n; ++j) // 遍历列
            cin >> a[i][j];       // 读入每个格子的值

    bfs();                        // 调用 BFS，标记所有外部连通的 0

    // 遍历内部区域，把所有未被访问的 0 改为 2
    for (int i = 1; i <= n; ++i)  // 实际方阵的行
        for (int j = 1; j <= n; ++j) // 实际方阵的列
            if (a[i][j] == 0 && !vis[i][j]) // 若为 0 且 BFS 未访问到
                a[i][j] = 2;       // 说明在闭合圈内，改为 2

    // 按格式输出结果
    for (int i = 1; i <= n; ++i) { // 每一行
        for (int j = 1; j <= n; ++j) // 每一列
            cout << a[i][j] << " \n"[j == n]; // 输出数字，行末换行，数字间空格
    }
    return 0;                     // 程序正常结束
}
